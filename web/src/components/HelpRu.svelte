<section id="help-start">
  <h2>Начало работы</h2>
  <p>
    Это приложение управляет одним DSP t.racks (408, 206 или 204) по сети. Его могут
    одновременно открыть все телефоны, планшеты и компьютеры в той же сети, введя код доступа.
    Все видят одни и те же настройки и индикаторы уровня в реальном времени.
  </p>
  <ul>
    <li>
      <strong>Изменения применяются сразу:</strong> движение регулятора сразу меняет звук.
      Ничего «отправлять» не нужно.
    </li>
    <li>
      <strong>Настройки хранятся в DSP.</strong> Чтобы сохранить конфигурацию после выключения
      DSP или загрузки другого пресета, запишите её в пресет (см. <em>Пресеты</em>).
    </li>
    <li>Подключение к интернету не требуется.</li>
  </ul>
</section>

<section id="help-rail">
  <h2>Боковая панель</h2>
  <p>Панель слева одинакова во всех видах. Сверху вниз:</p>
  <dl>
    <dt>»</dt>
    <dd>Разворачивает панель, показывая названия вкладок; нажмите ещё раз, чтобы свернуть.</dd>
    <dt>DSP (точка, имя и модель)</dt>
    <dd>
      DSP, которым управляет эта вкладка. Точка зелёная, когда он на связи, и красная, когда DSP или сервер недоступны: тогда баннер вверху показывает, что именно (<em>СЕРВЕР</em> или <em>DSP</em>). Показаны последние известные значения, а элементы управления отключены, пока связь не восстановится сама (<em>Повторить сейчас</em> — попробовать сразу). Нажмите, чтобы увидеть список DSP сервера (например, основной системы и линии задержки): состояние, пресет и несохранённые изменения; нажмите на нужный, чтобы перейти к нему. Каждая вкладка браузера может показывать свой DSP. <em>Взять управление</em> действует на все DSP сервера.
    </dd>
    <dt>Пресет</dt>
    <dd>
